"""apply_sql_migrations under DEFERRABLE INITIALLY DEFERRED foreign keys.

Spec:         ``.kiro/specs/admissions-v2-canonical-rebuild/`` task 13.6 §8.1 L3
Requirements: **R15.7-R15.8** (a restored backup SHALL be able to be brought
              forward), **R18.7** (rehearsed before it reaches production)
Findings:     **GATE-13.4-02**, second layer
Evidence:     ``docs/v2-evidence/13.6/remediation/L2-L3/README.md``;
              measurement ``…/raw/07-pending-trigger-diagnosis.txt``

WHAT THESE TESTS PIN
--------------------
``_apply_transactional`` sends a whole migration file as ONE statement string
inside ONE transaction. On a database carrying Django-created
``DEFERRABLE INITIALLY DEFERRED`` foreign keys - which every production-lineage
database here does, alongside the hand-written non-deferrable duplicates - a row
write queues its referential-integrity check to COMMIT instead of to
end-of-statement, and Postgres then refuses later DDL on that same relation
inside the same transaction::

    cannot CREATE INDEX "programs" because it has pending trigger events
    cannot ALTER TABLE "applications" because it has pending trigger events

That is why a restored production-lineage backup could not be brought forward
even after the ``canonical_programs.id`` default was restored: the June
multi-tenant script backfills ``programs`` and ``applications`` and then indexes
both. The runner now opens each migration's transaction with
``SET CONSTRAINTS ALL IMMEDIATE``.

The three cases below are the whole contract:

1. a backfill-then-index file APPLIES (the defect is gone),
2. a genuine referential violation STILL FAILS the migration and still leaves
   ``migration_history`` unwritten (the fix is stricter, not weaker),
3. IMMEDIATE mode is really in effect *during* the file, not merely at COMMIT -
   which also documents the single behaviour this change gives up.

Postgres-only: the defect is a Postgres deferred-trigger interaction and SQLite
has no deferrable-constraint mode to exercise.
"""
from __future__ import annotations

from io import StringIO
from pathlib import Path

import pytest
from django.core.management import call_command
from django.core.management.base import CommandError
from django.db import connection

pytestmark = pytest.mark.skipif(
    connection.vendor != "postgresql",
    reason="deferred-constraint behaviour is Postgres-specific",
)

_PARENT = "_aux_deferred_parent"
_CHILD = "_aux_deferred_child"
_INDEX = "idx_aux_deferred_child_parent_id"

_MIGRATION_HISTORY_DDL = """
CREATE TABLE migration_history (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    migration_name TEXT NOT NULL,
    applied_at TIMESTAMPTZ NULL,
    checksum TEXT NULL,
    notes TEXT NULL
);
CREATE UNIQUE INDEX uq_migration_history_migration_name
    ON migration_history (migration_name);
"""

# The shape that reproduces the defect: the child's foreign key is
# ``DEFERRABLE INITIALLY DEFERRED``, exactly as Django's schema editor creates
# every foreign key it manages.
_FIXTURE_DDL = f"""
CREATE TABLE {_PARENT} (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name text NOT NULL
);
CREATE TABLE {_CHILD} (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    parent_id uuid NULL,
    label text NULL,
    CONSTRAINT {_CHILD}_parent_fk FOREIGN KEY (parent_id)
        REFERENCES {_PARENT} (id) DEFERRABLE INITIALLY DEFERRED
);
"""


def _exec(sql: str) -> None:
    with connection.cursor() as cur:
        for statement in [s.strip() for s in sql.split(";") if s.strip()]:
            cur.execute(statement)


@pytest.fixture
def deferred_fk_tables():
    """A parent/child pair whose foreign key is INITIALLY DEFERRED."""
    _exec(f"DROP TABLE IF EXISTS {_CHILD}; DROP TABLE IF EXISTS {_PARENT}")
    _exec(_FIXTURE_DDL)
    yield
    _exec(f"DROP TABLE IF EXISTS {_CHILD}; DROP TABLE IF EXISTS {_PARENT}")


@pytest.fixture
def migration_history_table():
    _exec(
        "DROP INDEX IF EXISTS uq_migration_history_migration_name;"
        " DROP TABLE IF EXISTS migration_history"
    )
    _exec(_MIGRATION_HISTORY_DDL)
    yield
    _exec(
        "DROP INDEX IF EXISTS uq_migration_history_migration_name;"
        " DROP TABLE IF EXISTS migration_history"
    )


@pytest.fixture
def migrations_dir(tmp_path) -> Path:
    directory = tmp_path / "scripts"
    directory.mkdir()
    return directory


def _recorded() -> set[str]:
    with connection.cursor() as cur:
        cur.execute("SELECT migration_name FROM migration_history")
        return {row[0] for row in cur.fetchall()}


def _index_exists(name: str) -> bool:
    with connection.cursor() as cur:
        cur.execute("SELECT to_regclass(%s)", [name])
        return cur.fetchone()[0] is not None


def _count(table: str) -> int:
    with connection.cursor() as cur:
        # Interpolated, but only ever from the two module-level literals above.
        cur.execute(f"SELECT count(*) FROM {table}")
        return cur.fetchone()[0]


@pytest.mark.django_db(transaction=True)
def test_backfill_then_index_on_deferred_fk_table_applies(
    deferred_fk_tables, migration_history_table, migrations_dir
):
    """A file that writes rows and then indexes the same table applies.

    This is GATE-13.4-02's second layer in miniature. Before the runner issued
    ``SET CONSTRAINTS ALL IMMEDIATE`` this raised
    ``cannot CREATE INDEX "_aux_deferred_child" because it has pending trigger
    events`` - the same error that stopped a restored production-lineage backup
    from being brought forward.
    """
    (migrations_dir / "0001_backfill_then_index.sql").write_text(
        f"""
        INSERT INTO {_PARENT} (name) VALUES ('canonical');
        INSERT INTO {_CHILD} (parent_id, label)
            SELECT id, 'linked' FROM {_PARENT};
        CREATE INDEX IF NOT EXISTS {_INDEX} ON {_CHILD} (parent_id);
        """
    )

    out = StringIO()
    call_command(
        "apply_sql_migrations",
        "--migrations-dir",
        str(migrations_dir),
        stdout=out,
        stderr=StringIO(),
    )

    assert "0001_backfill_then_index.sql" in _recorded()
    assert _index_exists(_INDEX), "the index the migration declared was not created"
    assert _count(_CHILD) == 1


@pytest.mark.django_db(transaction=True)
def test_referential_violation_still_fails_the_migration(
    deferred_fk_tables, migration_history_table, migrations_dir
):
    """Checking sooner is not checking less.

    The deferred check still runs inside the migration's own transaction, so a
    row pointing at a parent that does not exist still aborts the file, still
    rolls the write back, and still leaves ``migration_history`` unwritten.
    """
    (migrations_dir / "0001_violating.sql").write_text(
        f"""
        INSERT INTO {_CHILD} (parent_id, label)
            VALUES ('00000000-0000-0000-0000-000000000001', 'orphan');
        """
    )

    with pytest.raises(CommandError) as exc:
        call_command(
            "apply_sql_migrations",
            "--migrations-dir",
            str(migrations_dir),
            stdout=StringIO(),
            stderr=StringIO(),
        )

    assert "0001_violating.sql" in str(exc.value)
    assert _recorded() == set(), "a failed migration must not be recorded"
    assert _count(_CHILD) == 0, "the failed migration's write must be rolled back"


@pytest.mark.django_db(transaction=True)
def test_immediate_mode_is_in_effect_during_the_file(
    deferred_fk_tables, migration_history_table, migrations_dir
):
    """The mode is IMMEDIATE while the file runs, not just at COMMIT.

    Also the one capability this change gives up, pinned deliberately rather
    than discovered later: a file may no longer hold a foreign key violated
    across statement boundaries and repair it before COMMIT. Under the previous
    INITIALLY DEFERRED behaviour the file below committed cleanly, because the
    offending row was gone by the time the deferred check ran. It now fails at
    the offending statement. No migration in ``backend/scripts/`` relies on
    that - the whole 44-file sweep applies clean on the rehearsal database
    (``docs/v2-evidence/13.6/remediation/L2-L3/raw/08-sweep-after-run2.txt``) -
    and the additive-only contract does not permit it in the first place.
    """
    (migrations_dir / "0001_transiently_violating.sql").write_text(
        f"""
        INSERT INTO {_CHILD} (parent_id, label)
            VALUES ('00000000-0000-0000-0000-000000000002', 'transient');
        DELETE FROM {_CHILD} WHERE label = 'transient';
        """
    )

    with pytest.raises(CommandError):
        call_command(
            "apply_sql_migrations",
            "--migrations-dir",
            str(migrations_dir),
            stdout=StringIO(),
            stderr=StringIO(),
        )

    assert _recorded() == set()
    assert _count(_CHILD) == 0
